# 사용법:
#   python3 tools/pokerogue_import/import_passives.py \
#       --pokerogue-src /path/to/pokerogue/src \
#       --output        src/data/rogue/passive_data.generated.h

import sys as _sys

def _passive_main():
    import argparse as _ap
    parser = _ap.ArgumentParser(description="PokéRogue 패시브 데이터 변환")
    parser.add_argument("--pokerogue-src", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    src = Path(args.pokerogue_src)
    out = Path(args.output)

    # PokéRogue 어빌리티 파일 위치
    ability_file = src / "data" / "ability.ts"
    if not ability_file.exists():
        ability_file = src / "data" / "abilities.ts"
    if not ability_file.exists():
        print("[WARN] ability.ts not found. 기본 passive_data.h를 유지합니다.")
        return

    text = ability_file.read_text(encoding="utf-8")

    # 간단한 패턴 추출 (실제로는 더 정교한 파서 필요)
    # Ability.SPEED_BOOST, Ability.DROUGHT, etc.
    ability_pattern = re.compile(r'Abilities\.(\w+)')
    abilities = sorted(set(ability_pattern.findall(text)))

    lines = []
    lines.append("// AUTO-GENERATED by import_passives.py — DO NOT EDIT")
    lines.append("")
    lines.append("// 추출된 어빌리티 목록 (참고용)")
    lines.append(f"// 총 {len(abilities)}개")
    lines.append("// 실제 패시브 구현은 rogue_passive.c 참조")
    lines.append("")
    for ab in abilities[:50]:  # 상위 50개만
        lines.append(f"// Ability.{ab} → PASSIVE_xxx (수동 매핑 필요)")

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"[+] 패시브 참고 파일 생성: {out}")


if __name__ == "__main__" and "--passive" in _sys.argv:
    _sys.argv.remove("--passive")
    _passive_main()
